    private val TODAS: Map<String, Map<String, String>> =
        IDIOMAS_SOPORTADOS.associateWith { lang ->
            TRADUCCIONES[lang].orEmpty() +
                NUEVAS[lang].orEmpty() +
                NUEVAS2[lang].orEmpty() +
                NUEVAS3[lang].orEmpty()
        }

    fun t(idioma: String, clave: String): String =
        TODAS[idioma]?.get(clave)
            ?: TODAS["es"]?.get(clave)
            ?: clave
